#ifndef BS_STATUS_H
#define BS_STATUS_H
/* 函数调用结果，不表示系统故障的持续状态。 */
typedef enum {
    BS_STATUS_OK = 0, BS_STATUS_INVALID_ARGUMENT,
    BS_STATUS_NOT_INITIALIZED, BS_STATUS_INVALID_STATE,
    BS_STATUS_BUSY, BS_STATUS_EMPTY, BS_STATUS_NO_RESOURCES,
    BS_STATUS_OVERFLOW, BS_STATUS_TIMEOUT, BS_STATUS_UNSUPPORTED,
    BS_STATUS_NOT_AUTHORIZED, BS_STATUS_IO_ERROR, BS_STATUS_DATA_INVALID
} bs_status_t;
#endif
